import { afterEach, expect, test, vi } from 'vitest'
import { MediaTransport } from './transport'
afterEach(() => vi.restoreAllMocks())
test('an old play rejection cannot mark a replacement source failed', async () => {
  const audio = document.createElement('audio')
  let reject!: (reason: Error) => void
  vi.spyOn(audio, 'play').mockImplementation(() => new Promise((_resolve, fail) => { reject = fail }))
  const transport = new MediaTransport()
  const detach = transport.attach(audio)
  audio.src = '/synthetic/first.wav'; transport.reset(10); transport.play()
  audio.src = '/synthetic/second.wav'; transport.reset(90)
  reject(new Error('Synthetic first-source failure')); await Promise.resolve(); await Promise.resolve()
  expect(transport.snapshot.duration).toBe(90)
  expect(transport.snapshot.failed).toBe(false)
  detach()
})
test('cleanup from an older attachment cannot detach its successor', () => {
  const first = document.createElement('audio'), second = document.createElement('audio')
  const transport = new MediaTransport(), onPlay = vi.fn()
  transport.setCallbacks({ onPlay })
  const retireFirst = transport.attach(first)
  const retireSecond = transport.attach(second)
  retireFirst()
  second.dispatchEvent(new Event('play'))
  expect(onPlay).toHaveBeenCalledTimes(1)
  expect(transport.snapshot.playing).toBe(true)
  retireSecond()
})

test('pause and a newer play intent retire previous play failures; owned failure reports once', async () => {
  const audio = document.createElement('audio'), transport = new MediaTransport(), onError = vi.fn()
  let reject!: (reason: Error) => void
  vi.spyOn(audio, 'play').mockImplementationOnce(() => new Promise((_yes, fail) => { reject = fail })).mockResolvedValue(undefined)
  transport.setCallbacks({ onError }); const detach = transport.attach(audio)
  transport.play(); transport.pause(); transport.play()
  reject(new Error('Old attempt')); await Promise.resolve(); await Promise.resolve()
  expect(transport.snapshot.failed).toBe(false); expect(onError).not.toHaveBeenCalled()
  audio.dispatchEvent(new Event('error')); audio.dispatchEvent(new Event('error'))
  expect(onError).toHaveBeenCalledTimes(1); detach()
})
test('a playback group pauses only attached peers and detachment releases its own playback', () => {
  const first = document.createElement('audio'), second = document.createElement('audio'), other = document.createElement('audio')
  for (const node of [first, second, other]) Object.defineProperty(node, 'paused', { configurable: true, value: false })
  const pauseFirst = vi.spyOn(first, 'pause').mockImplementation(() => {}), pauseOther = vi.spyOn(other, 'pause').mockImplementation(() => {}), pauseSecond = vi.spyOn(second, 'pause').mockImplementation(() => {})
  const a = new MediaTransport(), b = new MediaTransport(), c = new MediaTransport()
  a.setPlaybackGroup('comparison'); b.setPlaybackGroup('comparison')
  const da = a.attach(first), db = b.attach(second), dc = c.attach(other)
  second.dispatchEvent(new Event('play'))
  expect(pauseFirst).toHaveBeenCalledTimes(1); expect(pauseOther).not.toHaveBeenCalled()
  db(); expect(pauseSecond).toHaveBeenCalledTimes(1)
  da(); dc()
})
test('absolute chapter seeking accepts pre-metadata intent and rejects invalid values', () => {
  const audio = document.createElement('audio'), transport = new MediaTransport(), detach = transport.attach(audio)
  expect(transport.seekTo(12)).toBe(true); expect(audio.currentTime).toBe(12)
  expect(transport.seekTo(-1)).toBe(false); expect(transport.seekTo(NaN)).toBe(false)
  expect(audio.currentTime).toBe(12)
  transport.reset(20); transport.seekTo(100); expect(audio.currentTime).toBe(20)
  detach()
})
