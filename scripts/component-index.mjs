#!/usr/bin/env node
// Generates components.md from the real public package surface: the
// package.json exports map, the Svelte components each subpath re-exports, and
// the docs route that documents it. src/componentIndex.test.ts fails when the
// committed file differs from a fresh run.
//
//   node scripts/component-index.mjs           # write components.md
//   node scripts/component-index.mjs --check   # exit 1 if stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { DOC_EXEMPT, GROUPED_DOCS } from './component-docs-map.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = path.join(ROOT, 'components.md')

const read = (relative) => readFileSync(path.join(ROOT, relative), 'utf8')

function resolveModule(from, specifier) {
  const candidate = path.resolve(ROOT, path.dirname(from), specifier)
  for (const file of [candidate, `${candidate}.ts`, path.join(candidate, 'index.ts')]) {
    if (existsSync(file) && file.endsWith('.ts')) return path.relative(ROOT, file)
  }
  return null
}

/** Svelte components and runtime (non-type) named exports reachable from a barrel. */
function surface(file, visited = new Set()) {
  const result = { components: new Set(), values: new Set() }
  if (visited.has(file)) return result
  visited.add(file)
  const source = read(file)
  for (const [, name] of source.matchAll(/export\s*\{\s*default\s+as\s+(\w+)\s*\}\s*from\s*['"][^'"]+\.svelte['"]/g)) result.components.add(name)
  for (const [, isType, body, specifier] of source.matchAll(/export\s+(type\s+)?\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/g)) {
    if (isType || specifier.endsWith('.svelte')) continue
    for (const entry of body.split(',')) {
      const cleaned = entry.trim()
      if (!cleaned || cleaned.startsWith('type ')) continue
      result.values.add((cleaned.split(/\s+as\s+/).pop() ?? cleaned).trim())
    }
  }
  for (const [, specifier] of source.matchAll(/export\s+\*\s+from\s+['"]([^'"]+)['"]/g)) {
    // Deprecated aliases live under compatibility/ and are not part of the index.
    if (/(^|\/)compatibility(\/|$)/.test(specifier)) continue
    const target = resolveModule(file, specifier)
    if (!target) continue
    const nested = surface(target, visited)
    for (const name of nested.components) result.components.add(name)
    for (const name of nested.values) result.values.add(name)
  }
  for (const name of result.components) result.values.delete(name)
  return result
}

function docRoutes() {
  const routes = new Map()
  const pattern = /\{\s*path:\s*'components\/([^']+)',\s*label:\s*'((?:\\'|[^'])*)',\s*group:\s*'([^']+)',\s*description:\s*'((?:\\'|[^'])*)'/g
  for (const [, slug, label, group, description] of read('src/docs/svelte/routes.ts').matchAll(pattern)) {
    routes.set(slug, { label: label.replace(/\\'/g, "'"), group, description: description.replace(/\\'/g, "'") })
  }
  return routes
}

const cell = (text) => text.replace(/\|/g, '\\|')

export function renderIndex() {
  const manifest = JSON.parse(read('package.json'))
  const routes = docRoutes()
  const used = new Set()
  const modules = []
  const styles = []
  for (const [subpath, target] of Object.entries(manifest.exports)) {
    if (!target.endsWith('.ts')) { styles.push([subpath, target]); continue }
    const name = subpath === '.' ? '' : subpath.slice(2)
    const slug = GROUPED_DOCS[name] ?? name
    const route = routes.get(slug)
    if (route) used.add(slug)
    modules.push({ subpath, target, name, slug, route, ...surface(target.slice(2)) })
  }

  const lines = [
    '# Tint component index',
    '',
    '<!-- Generated by scripts/component-index.mjs. Do not edit; run `node scripts/component-index.mjs`. -->',
    '',
    'Every public package subpath, the Svelte components it exports, and the docs page',
    'that documents it. Import from these subpaths only; internal source paths are not API.',
    'How to add a component: [CONTRIBUTING.md](CONTRIBUTING.md). Design rules:',
    '[docs/style-guide.md](docs/style-guide.md).',
    '',
  ]
  const groups = new Map()
  for (const module of modules) {
    const group = module.subpath === '.' ? 'Root' : module.route?.group ?? (DOC_EXEMPT.has(module.name) ? 'Bindings and transports' : 'Undocumented')
    if (!groups.has(group)) groups.set(group, [])
    groups.get(group).push(module)
  }
  const order = ['Root', 'Foundation', 'Forms', 'Interaction', 'Data', 'Feedback']
  const names = [...groups.keys()].sort((a, b) => {
    const rank = (name) => { const index = order.indexOf(name); return index < 0 ? order.length + (name === 'Undocumented' ? 1 : 0) : index }
    return rank(a) - rank(b) || a.localeCompare(b)
  })
  let componentCount = 0
  for (const group of names) {
    lines.push(`## ${group}`, '', '| Import | Components | Docs page | Purpose |', '|---|---|---|---|')
    for (const module of groups.get(group).sort((a, b) => a.subpath.localeCompare(b.subpath))) {
      const specifier = module.subpath === '.' ? '@nebula/tint' : `@nebula/tint/${module.name}`
      const components = [...module.components].sort()
      componentCount += module.subpath === '.' ? 0 : components.length
      const listed = module.subpath === '.' ? `${components.length} re-exported` : components.length ? components.map((name) => `\`${name}\``).join(', ') : '—'
      const page = module.route ? `${cell(module.route.label)} (\`#/components/${module.slug}\`)` : module.subpath === '.' ? 'All pages' : '—'
      const purpose = module.route ? (module.slug !== module.name && module.name ? `Shares the ${cell(module.route.label)} page.` : cell(module.route.description))
        : module.subpath === '.' ? 'Root barrel: every public Svelte component.' : `${[...module.values].length} runtime exports; no docs page.`
      lines.push(`| \`${specifier}\` | ${listed} | ${page} | ${purpose} |`)
    }
    lines.push('')
  }
  lines.push('## Stylesheets', '', '| Import | Source |', '|---|---|')
  for (const [subpath, target] of styles.sort((a, b) => a[0].localeCompare(b[0]))) lines.push(`| \`@nebula/tint/${subpath.slice(2)}\` | \`${target.slice(2)}\` |`)
  lines.push('')
  const orphanRoutes = [...routes.keys()].filter((slug) => !used.has(slug)).sort()
  lines.push('## Docs pages without a package subpath', '')
  lines.push(orphanRoutes.length ? orphanRoutes.map((slug) => `- \`#/components/${slug}\`: ${cell(routes.get(slug).label)}`).join('\n') : 'None.')
  lines.push('', `Totals: ${modules.length} module subpaths, ${styles.length} stylesheets, ${componentCount} component exports across subpaths (a component exported from two subpaths counts twice).`, '')
  return lines.join('\n')
}

function main(argv) {
  const next = renderIndex()
  if (argv.includes('--check')) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : ''
    if (current !== next) { console.error('components.md is stale: run node scripts/component-index.mjs'); return 1 }
    console.log('components.md is current.')
    return 0
  }
  writeFileSync(OUTPUT, next)
  console.log(`wrote ${path.relative(process.cwd(), OUTPUT)}`)
  return 0
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) process.exitCode = main(process.argv.slice(2))
