import { Buffer } from 'node:buffer'
import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  const samples = 16000 * 20, wave = Buffer.alloc(44 + samples * 2)
  wave.write('RIFF', 0); wave.writeUInt32LE(wave.length - 8, 4); wave.write('WAVEfmt ', 8); wave.writeUInt32LE(16, 16)
  wave.writeUInt16LE(1, 20); wave.writeUInt16LE(1, 22); wave.writeUInt32LE(16000, 24); wave.writeUInt32LE(32000, 28)
  wave.writeUInt16LE(2, 32); wave.writeUInt16LE(16, 34); wave.write('data', 36); wave.writeUInt32LE(samples * 2, 40)
  await page.route('**/audio/avery.wav', route => route.fulfill({ contentType: 'audio/wav', body: wave }))
})

test('linked audio preserves native playback exclusion, repeated chapter seeks and teardown', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/components/media')
  await page.getByRole('button', { name: 'Show linked previews' }).click()
  const previews = page.getByRole('region', { name: 'Linked playback previews' })
  const first = previews.locator('audio[aria-label="First preview"]'), second = previews.locator('audio[aria-label="Second preview"]')
  await expect(first).toHaveAttribute('preload', 'none')
  await previews.getByRole('button', { name: 'Play First preview' }).click()
  await expect.poll(() => first.evaluate(node => (node as HTMLAudioElement).paused)).toBe(false)
  await previews.getByRole('button', { name: 'Play Second preview' }).click()
  await expect.poll(() => second.evaluate(node => (node as HTMLAudioElement).paused)).toBe(false)
  await expect.poll(() => first.evaluate(node => (node as HTMLAudioElement).paused)).toBe(true)
  await previews.getByRole('button', { name: 'Play chapter at 1 second' }).click()
  await expect.poll(() => first.evaluate(node => (node as HTMLAudioElement).currentTime)).toBeGreaterThanOrEqual(1)
  await expect.poll(() => second.evaluate(node => (node as HTMLAudioElement).paused)).toBe(true)
  await first.evaluate(node => { (node as HTMLAudioElement).currentTime = 10 })
  await previews.getByRole('button', { name: 'Play chapter at 1 second' }).click()
  await expect.poll(() => first.evaluate(node => (node as HTMLAudioElement).currentTime)).toBeLessThan(3)
  const retired = await first.elementHandle()
  await page.evaluate(() => { location.hash = '#/components/shell' })
  await expect(page.getByRole('heading', { name: 'Shell and Workspace', exact: true })).toBeVisible()
  expect(await retired!.evaluate(node => ({ paused: (node as HTMLAudioElement).paused, connected: node.isConnected }))).toEqual({ paused: true, connected: false })
  expect(errors).toEqual([])
})

test('source replacement never replays a previous seek and reports its own native error', async ({ page }) => {
  await page.goto('/#/components/media')
  await page.getByRole('button', { name: 'Show linked previews' }).click()
  const previews = page.getByRole('region', { name: 'Linked playback previews' })
  await previews.getByRole('button', { name: 'Play chapter at 1 second' }).click()
  const original = await previews.locator('audio[aria-label="First preview"]').elementHandle()
  await expect.poll(() => original!.evaluate(node => (node as HTMLAudioElement).paused)).toBe(false)
  await previews.getByRole('button', { name: 'Use missing preview' }).click()
  expect(await original!.evaluate(node => (node as HTMLAudioElement).paused)).toBe(true)
  const current = previews.locator('audio[aria-label="First preview"]')
  expect(await current.evaluate(node => (node as HTMLAudioElement).paused)).toBe(true)
  await previews.getByRole('button', { name: 'Play First preview' }).click()
  await expect(previews.getByRole('status')).toHaveText('Preview unavailable: /audio/missing-preview.wav')
})
