import { expect, test } from '@playwright/test'

test('editor slash completion shares the listbox, preserves pointer focus and cleans up', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/components/editor')
  const editor = page.getByRole('textbox', { name: 'Demo article body' })
  await editor.click()
  await page.keyboard.press('Control+a')
  await page.keyboard.press('Backspace')
  await page.keyboard.type('/')
  const list = page.getByRole('listbox', { name: 'Insert block' })
  await expect(list).toBeVisible()
  await expect(list).toHaveAttribute('data-tint-command-menu', '')
  await expect(editor).toBeFocused()
  await expect(editor).toHaveAttribute('aria-controls', await list.getAttribute('id') ?? '')
  await page.keyboard.press('End')
  const last = list.getByRole('option').last()
  await expect(last).toHaveAttribute('aria-selected', 'true')
  await expect(editor).toHaveAttribute('aria-activedescendant', await last.getAttribute('id') ?? '')
  await page.keyboard.press('Home')
  await expect(list.getByRole('option').first()).toHaveAttribute('aria-selected', 'true')
  await list.getByRole('option', { name: /Heading 1/ }).click()
  await expect(editor.locator('h1')).toBeVisible()
  await expect(editor).toBeFocused()
  await expect(list).toHaveCount(0)
  await expect(editor).not.toHaveAttribute('aria-activedescendant', /.+/)
  await page.keyboard.type('/')
  await expect(list).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(list).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Read only' }).check()
  await expect(editor).toHaveAttribute('contenteditable', 'false')
  expect(errors).toEqual([])
})

test('palette uses shared options with keyboard identity and restores trigger focus', async ({ page }) => {
  await page.goto('/#/components/shell')
  const trigger = page.getByRole('button', { name: 'Open command palette' })
  await trigger.click()
  const input = page.getByRole('combobox', { name: 'Command palette' })
  const list = page.getByRole('listbox', { name: 'Command palette' })
  await expect(list).toHaveAttribute('data-tint-command-menu', '')
  await expect(input).toBeFocused()
  await input.press('End')
  await expect(input).toHaveAttribute('aria-activedescendant', await list.getByRole('option').last().getAttribute('id') ?? '')
  await input.fill('share')
  await expect(list.getByRole('option')).toHaveCount(1)
  await input.press('Enter')
  await expect(page.getByText('Selected command: share')).toBeVisible()
  await expect(trigger).toBeFocused()
})
